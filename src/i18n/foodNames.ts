/** Translates a food/ingredient name; falls back to the English original if not in the dictionary
 * (covers custom, user-typed ingredient names, which are never translated). */
export function foodName(name: string, lang: 'en' | 'it'): string {
  if (lang === 'en') return name;
  return FOOD_NAME_IT[name] ?? name;
}
